-- ===== V1__init_schema.sql =====
CREATE TABLE object_nodes (
    id VARCHAR2(64 CHAR) PRIMARY KEY,
    path VARCHAR2(512 CHAR) NOT NULL UNIQUE,
    type VARCHAR2(32 CHAR) NOT NULL,
    display_name VARCHAR2(256 CHAR) NOT NULL,
    description CLOB,
    template_id VARCHAR2(128 CHAR),
    created_at TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    events_json CLOB,
    functions_json CLOB
);
CREATE TABLE object_variables (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_path VARCHAR2(512 CHAR) NOT NULL,
    name VARCHAR2(128 CHAR) NOT NULL,
    schema_json CLOB NOT NULL,
    value_json CLOB,
    readable NUMBER(1) DEFAULT 1 NOT NULL CHECK (readable IN (0, 1)),
    writable NUMBER(1) DEFAULT 0 NOT NULL CHECK (writable IN (0, 1)),
    updated_at TIMESTAMP(6),
    UNIQUE (object_path, name)
);
CREATE TABLE event_history (
    id VARCHAR2(64 CHAR) PRIMARY KEY,
    object_path VARCHAR2(512 CHAR) NOT NULL,
    event_name VARCHAR2(128 CHAR) NOT NULL,
    "level" VARCHAR2(16 CHAR) NOT NULL,
    payload_json CLOB,
    occurred_at TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL
);
CREATE INDEX idx_event_history_object ON event_history (object_path, occurred_at DESC);
CREATE INDEX idx_object_variables_path ON object_variables (object_path);

