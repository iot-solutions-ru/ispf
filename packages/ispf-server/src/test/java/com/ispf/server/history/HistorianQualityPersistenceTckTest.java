import java.time.Instant;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

/**
 * ADR-0074: jdbc historian quality round-trip. ClickHouse proof is
 * {@link HistorianQualityClickHouseTckTest} (opt-in; default CI does not start Docker).
 * Cassandra/Scylla stays quality-incapable.
 */
class HistorianQualityPersistenceTckTest {

    @Test
    void jdbcRoundTripsGoodUncertainBadAndLeavesUnknownNull() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource();
        dataSource.setDriverClassName("org.h2.Driver");
        dataSource.setUrl(
                "jdbc:h2:mem:historian-quality;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1"
        );
        dataSource.setUsername("sa");
        dataSource.setPassword("");
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                CREATE TABLE variable_samples (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    object_path VARCHAR(512) NOT NULL,
                    variable_name VARCHAR(128) NOT NULL,
                    field_name VARCHAR(128) NOT NULL,
                    sampled_at TIMESTAMP NOT NULL,
                    observed_at TIMESTAMP NOT NULL,
                    value_double DOUBLE PRECISION,
                    value_text VARCHAR(2048),
                    quality VARCHAR(32)
                )
                """);

        JdbcVariableHistoryWriteStore store = new JdbcVariableHistoryWriteStore(jdbc);
        Instant t0 = Instant.parse("2026-10-13T08:00:00Z");
        store.appendBatch(List.of(
                sample(t0, "GOOD"),
                sample(t0.plusSeconds(1), "uncertain"),
                sample(t0.plusSeconds(2), "bad")
        ));
        store.appendOne(sample(t0.plusSeconds(3), null));
        store.appendOne(sample(t0.plusSeconds(4), " "));

        List<String> qualities = jdbc.query(
                "SELECT quality FROM variable_samples ORDER BY sampled_at",
                (rs, rowNum) -> rs.getString("quality")
        );
        assertEquals(List.of("GOOD", "UNCERTAIN", "BAD"), qualities.subList(0, 3));
        assertNull(qualities.get(3));
        assertNull(qualities.get(4));
    }

    @Test
    void jdbcQueryStoreReadsQuality() {
        VariableSampleRepository repository = mock(VariableSampleRepository.class);
        Instant ts = Instant.parse("2026-10-13T08:00:00Z");
        VariableSampleEntity entity = new VariableSampleEntity();
        entity.setSampledAt(ts);
        entity.setObservedAt(ts);
        entity.setValueDouble(1.5);
        entity.setQuality("UNCERTAIN");
        when(repository.findByObjectPathAndVariableNameAndFieldNameOrderByEffectiveTimestampDesc(
                eq("root.a"),
                eq("temperature"),
                eq("value"),
                any()
        )).thenReturn(List.of(entity));

        JdbcVariableHistoryQueryStore store = new JdbcVariableHistoryQueryStore(
                repository,
                mock(VariableSampleBucketQuery.class),
                mock(RelationalDialect.class),
                mock(TimescaleHypertableInitializer.class)
        );

        List<VariableHistoryService.VariableHistorySample> samples =
                store.query("root.a", "temperature", "value", null, null, 10);

        assertEquals(1, samples.size());
        assertEquals("UNCERTAIN", samples.getFirst().quality());
        assertEquals(1.5, samples.getFirst().value());
    }

    private static VariableHistoryWriteRecord sample(Instant at, String quality) {
        return VariableHistoryWriteRecord.ingested(
                "root.platform.devices.demo",
                "temperature",
                "value",
                at,
                21.5,
                null,
                quality
        );
    }
}
